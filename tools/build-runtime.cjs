#!/usr/bin/env node
// Crea un únic script clàssic amb els sistemes en l'ordre existent.
// Sense dependències npm: reproducible tant localment com a GitHub Actions.
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const root=path.resolve(__dirname,'..');
const check=process.argv.includes('--check');
function fnv64(s){
  let h=0xcbf29ce484222325n;
  for(let i=0;i<s.length;i++)h=BigInt.asUintN(64,(h^BigInt(s.charCodeAt(i)))*0x100000001b3n);
  return h.toString(16).padStart(16,'0');
}
async function main(){
  const {runtimeScripts}=await import(pathToFileURL(path.join(root,'src/runtime-scripts.mjs')).href);
  const bundle='// Generated by tools/build-runtime.cjs; do not edit manually.\n'
    +runtimeScripts.map(file=>'// BEGIN '+file+'\n'+fs.readFileSync(path.join(root,file),'utf8')+'\n;\n// END '+file+'\n').join('');
  const filename='hunter-runtime.'+fnv64(bundle)+'.js';
  const relative='dist/'+filename;
  const manifest='// Generated by tools/build-runtime.cjs; do not edit manually.\nexport const RUNTIME_BUNDLE_PATH = '+JSON.stringify(relative)+';\n';
  const dest=path.join(root,relative);
  const manifestPath=path.join(root,'src/runtime-bundle.mjs');
  if(check){
    if(!fs.existsSync(dest)||fs.readFileSync(dest,'utf8')!==bundle||
       !fs.existsSync(manifestPath)||fs.readFileSync(manifestPath,'utf8')!==manifest){
      throw new Error('Runtime bundle desactualitzat. Executa: node tools/build-runtime.cjs');
    }
  }else{
    fs.mkdirSync(path.dirname(dest),{recursive:true});
    fs.writeFileSync(dest,bundle);
    fs.writeFileSync(manifestPath,manifest);
    for(const file of fs.readdirSync(path.dirname(dest)))
      if(/^hunter-runtime\.[a-f0-9]{16}\.js$/.test(file)&&file!==filename)
        fs.unlinkSync(path.join(path.dirname(dest),file));
  }
  console.log((check?'OK ':'Generat ')+relative+' ('+runtimeScripts.length+' mòduls, '+bundle.length+' caràcters)');
}
main().catch(error=>{console.error(error);process.exitCode=1});
