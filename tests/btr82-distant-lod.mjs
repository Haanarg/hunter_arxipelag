import assert from 'node:assert/strict';
import * as THREE from '../vendor/three-r186.module.mjs';
import {installBtr82Model3B,createBtr82DistantGeometry} from '../src/btr82-3b-native.mjs';
import {createDistantVehicleFactory,setDistantVehicleLOD} from '../src/vehicle-distant-lod.mjs';
import {readFileSync} from 'node:fs';
const full=new THREE.Group();installBtr82Model3B(THREE,full);
full.updateMatrixWorld(true);
const geo=createBtr82DistantGeometry(THREE);
const meta=geo.userData.btr82Distant;
assert.equal(meta.wheels,8);assert.equal(meta.axles,4);
const wheels=full.userData.wheels.map(w=>w.getWorldPosition(new THREE.Vector3()));
assert.equal(wheels.length,8);
for(const center of meta.wheelCenters)assert(wheels.some(w=>w.distanceTo(new THREE.Vector3(...center))<1e-5));
const fullHull=full.getObjectByName('BTR82_3B_hull').geometry;
fullHull.computeBoundingBox();geo.computeBoundingBox();
assert(Math.abs(geo.boundingBox.min.z-fullHull.boundingBox.min.z)<.1);
assert(Math.abs(geo.boundingBox.max.z-fullHull.boundingBox.max.z)<.1);
assert(Math.abs(geo.boundingBox.min.y-.15)<.01);
assert(geo.getAttribute('position').count/3<1200,'LOD triangle budget');
assert.equal(geo.getAttribute('position').count,geo.getAttribute('color').count);
const factory=createDistantVehicleFactory(THREE);
const a=factory.attach(full,'tanqueta'),other=new THREE.Group(),b=factory.attach(other,'tanqueta');
assert.equal(a.variants[0],a.variants[2]);assert.equal(a.proxy.geometry,b.proxy.geometry);
assert(setDistantVehicleLOD(full,true));assert(a.proxy.visible&&!a.full.visible);
assert(setDistantVehicleLOD(full,false));assert(!a.proxy.visible&&a.full.visible);
globalThis.window={HUNTER_SHARED_VEHICLE_MODELS:{createBtr82DistantGeometry}};
new Function(readFileSync(new URL('../src/enemy-lod.js',import.meta.url),'utf8'))();
const enemy=new THREE.Group();factory.attach(enemy,'tanqueta');
window.HUNTER_ENEMY_LOD.optimize(THREE,enemy,'tanqueta');
assert.equal(enemy.userData.enemyMidMesh.geometry,a.proxy.geometry);
assert.equal(enemy.userData.enemyFarMesh.geometry,a.proxy.geometry);
assert(enemy.userData.enemyFlag);
window.HUNTER_ENEMY_LOD.setLevel(enemy,'far');assert(enemy.userData.enemyFarMesh.visible);
console.log('PASS BTR-82 LOD: eight real wheel positions, exact hull, single shared mesh and enemy parity');
