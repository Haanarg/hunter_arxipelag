import assert from 'node:assert/strict';
import {createOperation} from '../src/operation-save.mjs';
import {serializeSaveFile,parseSaveFile,MAX_SAVE_FILE_BYTES} from '../src/operation-files.mjs';
const snapshot=createOperation({operationId:'op:source',name:'Operació àgil <b>67</b>',gameVersion:'0.6.5',
  generatorVersion:'world:0.6.2',seed:67,mapScale:1,now:100});
const file=await serializeSaveFile(snapshot,{now:200});
assert.match(file.fileName,/^hunter-67-100\.hunter-save\.json$/);
assert.deepEqual(await parseSaveFile(file.text),snapshot);
assert.deepEqual(await parseSaveFile('\uFEFF'+file.text),snapshot);
assert.deepEqual(await parseSaveFile({size:file.text.length,text:async()=>file.text}),snapshot);
await assert.rejects(parseSaveFile('not JSON'),/JSON/);
const edited=JSON.parse(file.text);edited.payload.name='changed';
await assert.rejects(parseSaveFile(JSON.stringify(edited)),/verificació/);
const future=JSON.parse(file.text);future.fileVersion=99;
await assert.rejects(parseSaveFile(JSON.stringify(future)),/incompatible/);
let read=false;
await assert.rejects(parseSaveFile({size:MAX_SAVE_FILE_BYTES+1,text:async()=>{read=true;return file.text}}),/17 MiB/);
assert.equal(read,false,'oversized file rejected before reading bytes');
await assert.rejects(parseSaveFile({size:1,text:async()=> ' '.repeat(MAX_SAVE_FILE_BYTES+1)}),/17 MiB/);
const hostile=JSON.parse(file.text);hostile.payload.stats=JSON.parse('{"__proto__":{"polluted":true}}');
await assert.rejects(parseSaveFile(JSON.stringify(hostile)),/Propietat/);
assert.equal({}.polluted,undefined);
const broken=JSON.parse(file.text);broken.payload.format=99;
await assert.rejects(parseSaveFile(JSON.stringify(broken)),/incompatible/);
console.log('operation-files: UTF-8 roundtrip, file version, checksum, malformed JSON, size limit and prototype protection passed');
