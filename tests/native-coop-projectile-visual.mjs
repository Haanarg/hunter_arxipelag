import assert from 'node:assert/strict';
import {createNativeCoopProjectileVisual} from '../src/native-coop-projectile-visual.mjs';
const row=(id,x,overrides={})=>({id,x,y:1.5,z:0,vx:130,vy:0,vz:0,actorId:'a',weapon:'pistol',...overrides});
const close=(a,b,tolerance=.001)=>assert(Math.abs(a-b)<=tolerance,`${a} != ${b}`);
const tip={x:.75,y:1.5,z:0};
const local=createNativeCoopProjectileVisual(),real=row('bullet',13);
local.receive([real],'a',()=>tip);
let initial=0;local.advance(0,(_,p)=>initial=p.x);
close(initial,tip.x);assert.equal(local.stats.localMuzzleStarts,1);
const rendered=[];
for(let i=0;i<24;i++)local.advance(1/240,(_,pose)=>rendered.push(pose.x));
assert(rendered.every((x,i)=>!i||x>rendered[i-1]),'Bales avancen en cada frame, no sols cada 100 ms');
assert(rendered[0]>tip.x&&rendered.at(-1)>13);close(real.x,13);
const remote=createNativeCoopProjectileVisual();
remote.receive([row('remote',13,{actorId:'b'})],'a');
let last=13;for(let i=0;i<12;i++)remote.advance(1/240,(_,pose)=>last=pose.x);
remote.receive([row('remote',17,{actorId:'b'})],'a');
let after=0;remote.advance(0,(_,p)=>after=p.x);close(after,last);
remote.advance(1/60,(_,p)=>after=p.x);
assert(after>last,'El següent frame continua avançant sense salt de recepció');
assert.equal(remote.stats.corrections,1);
const same=row('same',2),stable=createNativeCoopProjectileVisual();
stable.receive([same],'a');let before=2;stable.advance(.08,(_,p)=>before=p.x);
stable.receive([same],'a');stable.advance(0,(_,p)=>close(p.x,before));
stable.receive([],'a');assert.equal(stable.stats.active,0);
let calls=0;stable.advance(.1,()=>calls++);assert.equal(calls,0);
const notOwn=createNativeCoopProjectileVisual();
notOwn.receive([row('far',200),row('enemy',8,{actorId:'enemy'}),
 row('backward',13,{vx:-130})],'a',()=>({x:0,y:1.5,z:0}));
assert.equal(notOwn.stats.localMuzzleStarts,0);
const old=new Map();notOwn.advance(0,(id,p)=>old.set(id,p.x));
close(old.get('far'),200);close(old.get('enemy'),8);close(old.get('backward'),13);
const bounded=createNativeCoopProjectileVisual();
bounded.receive([row('cap',0,{actorId:'other'})],'a');
let x=0;bounded.advance(.05,(_,p)=>x=p.x);close(x,6.5);
bounded.advance(0,(_,p)=>close(p.x,x));
bounded.advance(5,(_,p)=>x=p.x);close(x,19.5);
bounded.advance(5,(_,p)=>x=p.x);close(x,23.4);
bounded.advance(5,(_,p)=>close(p.x,23.4));
bounded.reset();assert.equal(bounded.stats.active,0);
console.log('native coop projectile visual: muzzle, continuous 240Hz movement, correction, identity, removal, bounded forecast passed');